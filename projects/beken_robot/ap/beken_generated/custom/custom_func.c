void ui_asr_demo_notify_zaijianbotong(void)
{
    s_asr_demo_phrase_trigger = 2;
}

int ui_asr_demo_consume_phrase_trigger(char *phrase_buf, int phrase_buf_len)
{
    int trigger = s_asr_demo_phrase_trigger;

    if (phrase_buf == NULL || phrase_buf_len <= 0) {
        return 0;
    }
    if (trigger == 0) {
        return 0;
    }

    if (trigger == 1) {
        snprintf(phrase_buf, phrase_buf_len, "nihaobotong");
    } else if (trigger == 2) {
        snprintf(phrase_buf, phrase_buf_len, "zaijianbotong");
    } else {
        return 0;
    }

    s_asr_demo_phrase_trigger = 0;
    return 1;
}

