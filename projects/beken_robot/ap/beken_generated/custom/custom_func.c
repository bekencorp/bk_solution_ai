    snprintf(s_asr_demo_state, sizeof(s_asr_demo_state), "识别中");
    snprintf(s_asr_demo_result, sizeof(s_asr_demo_result), "播放: %s", s_asr_demo_commands[s_asr_demo_cmd_idx]);
